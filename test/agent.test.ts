const hex = (b: Uint8Array) => Buffer.from(b).toString("hex");
const SECP256K1_N = secp256k1.Point.CURVE().n;

/**
 * Independent re-implementation of the server's check
 * (`exchange-sec-utils::signing::recover_secp256k1`): parse a 65-byte
 * `r||s||v` signature, refuse high-S, recover over the given digest, and return
 * the Ethereum address. Uses only @noble primitives, never src/agent.ts.
 */
function recoverAddress(digest: Uint8Array, signatureHex: string): string {
  assert.match(signatureHex, /^0x[0-9a-f]{130}$/);
  const sig = Buffer.from(signatureHex.slice(2), "hex");
  const v = sig[64];
  assert.ok(v === 27 || v === 28, `v must be 27 or 28, got ${v}`);
  const s = BigInt(`0x${hex(sig.subarray(32, 64))}`);
  assert.ok(s <= SECP256K1_N / 2n, "signature must be low-S");
  // noble's `recovered` format is recid(1) || r(32) || s(32).
  const recovered = new Uint8Array(65);
  recovered[0] = v - 27;
  recovered.set(sig.subarray(0, 64), 1);
  const pub = secp256k1.recoverPublicKey(recovered, digest, {
    prehash: false,
  });
  const uncompressed = secp256k1.Point.fromBytes(pub).toBytes(false);
  return `0x${hex(keccak_256(uncompressed.subarray(1)).subarray(12))}`;
}


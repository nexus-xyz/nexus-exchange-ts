// -- recovery ------------------------------------------------------------------

test("signature recovers to x-agent over the UNPREFIXED keccak256", () => {
  const signer = AgentSigner.fromHex(VECTORS[1].private_key);
  const parts = {
    method: "POST",
    path: "/api/v1/orders",
    query: "",
    body: "{}",
    timestampMs: 1_776_033_900_000,
    nonce: 7,
  };
  const headers = signer.sign(parts);
  const canonical = new TextEncoder().encode(agentCanonicalString(parts));

  assert.equal(
    recoverAddress(keccak_256(canonical), headers["x-signature"]),
    headers["x-agent"],
  );

  // An EIP-191 prefix must not creep into the prehash: under the prefixed
  // digest the same signature recovers to some other address.
  const prefix = new TextEncoder().encode(
    `\x19Ethereum Signed Message:\n${canonical.length}`,
  );
  const prefixed = keccak_256(Buffer.concat([prefix, canonical]));
  assert.notEqual(
    recoverAddress(prefixed, headers["x-signature"]),
    headers["x-agent"],
  );
});

test("every spec vector signature recovers to its x-agent", () => {
  for (const v of VECTORS) {
    const digest = Buffer.from(v.digest.slice(2), "hex");
    assert.equal(recoverAddress(digest, v["x-signature"]), v["x-agent"]);
  }
});

// -- nonces --------------------------------------------------------------------

test("nonce is max(last + 1, timestamp) and strictly increases", () => {
  const signer = AgentSigner.fromHex(VECTORS[0].private_key);
  const nonce = (ts: number) =>
    Number(
      signer.authHeaders({ method: "POST", path: "/orders", timestampMs: ts })[
        "x-nonce"
      ],
    );
  assert.equal(nonce(1_000), 1_000);
  // Two requests in the same millisecond still get distinct nonces.
  assert.equal(nonce(1_000), 1_001);
  // A clock that steps backwards does not regress the nonce.
  assert.equal(nonce(500), 1_002);
  // Once the clock moves past the counter, the nonce follows the clock.
  assert.equal(nonce(5_000), 5_000);
});

test("authHeaders stamps x-timestamp with the request time, not the nonce", () => {
  const signer = AgentSigner.fromHex(VECTORS[0].private_key);
  signer.nextNonce(10_000);
  const h = signer.authHeaders({
    method: "GET",
    path: "/a",
    timestampMs: 2_000,
  });
  assert.equal(h["x-timestamp"], "2000");
  assert.equal(h["x-nonce"], "10001");
});

test("sign() with an explicit nonce does not advance the signer", () => {
  const signer = AgentSigner.fromHex(VECTORS[0].private_key);
  signer.sign({ method: "POST", path: "/o", timestampMs: 1, nonce: 99_999 });
  assert.equal(signer.nextNonce(1), 1);
});

test("nonces are unique across interleaved async callers", async () => {
  const signer = AgentSigner.fromHex(VECTORS[0].private_key);
  const all = await Promise.all(
    Array.from({ length: 200 }, async (_, i) => {
      await new Promise((r) => setImmediate(r));
      return signer.nextNonce(i % 7);
    }),
  );
  assert.equal(new Set(all).size, all.length);
});

test("out-of-range timestamps and nonces are refused, not signed", () => {
  const signer = AgentSigner.fromHex(VECTORS[0].private_key);
  for (const bad of [-1, 1.5, Number.NaN, 2 ** 53]) {
    assert.throws(
      () =>
        signer.sign({ method: "GET", path: "/", timestampMs: bad, nonce: 1 }),
      NexusExchangeError,
    );
    assert.throws(
      () =>
        signer.sign({ method: "GET", path: "/", timestampMs: 1, nonce: bad }),
      NexusExchangeError,
    );
  }
});


for (const v of VECTORS) {
  test(`spec vector: ${v.method} ${v.path}${v.query ? `?${v.query}` : ""}`, () => {
    const signer = AgentSigner.fromHex(v.private_key);
    assert.equal(signer.address, v["x-agent"]);

    const parts = {
      method: v.method,
      path: v.path,
      query: v.query,
      body: v.body,
      timestampMs: Number(v["x-timestamp"]),
      nonce: Number(v["x-nonce"]),
    };
    const canonical = agentCanonicalString(parts);
    assert.equal(canonical, v.canonical_string);
    assert.equal(
      `0x${hex(keccak_256(new TextEncoder().encode(canonical)))}`,
      v.digest,
    );

    // Byte-for-byte: the whole header set, nothing more and nothing less.
    assert.deepEqual(signer.sign(parts), {
      "x-agent": v["x-agent"],
      "x-timestamp": v["x-timestamp"],
      "x-nonce": v["x-nonce"],
      "x-signature": v["x-signature"],
    });
    // A body given as bytes signs identically to the same body as a string.
    assert.deepEqual(
      signer.sign({ ...parts, body: new TextEncoder().encode(v.body) }),
      signer.sign(parts),
    );
  });
}


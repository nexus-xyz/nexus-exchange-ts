interface Received {
  method: string;
  path: string;
  query: string;
  headers: IncomingMessage["headers"];
  body: Buffer;
}

/**
 * A real HTTP server that verifies agent auth the way the accounts service
 * does (`agent_verify::try_authenticate_agent`), independently of src/agent.ts:
 * ±30 s window, ecrecover over unprefixed keccak256(canonical) must equal
 * `x-agent`, and a strictly increasing nonce on mutating methods only.
 * Answers 401 on any failure, like the server.
 */
async function withAgentVerifier(
  nowMs: number,
  run: (baseUrl: string, received: Received[]) => Promise<void>,
): Promise<void> {
  const received: Received[] = [];
  const lastNonce = new Map<string, bigint>();
  const server = createServer((req, res) => {
    const chunks: Buffer[] = [];
    req.on("data", (c: Buffer) => chunks.push(c));
    req.on("end", () => {
      const body = Buffer.concat(chunks);
      const raw = req.url ?? "/";
      const q = raw.indexOf("?");
      const path = q === -1 ? raw : raw.slice(0, q);
      const query = q === -1 ? "" : raw.slice(q + 1);
      const method = req.method ?? "GET";
      received.push({ method, path, query, headers: req.headers, body });

      const agent = String(req.headers["x-agent"] ?? "");
      const ts = String(req.headers["x-timestamp"] ?? "");
      const nonce = String(req.headers["x-nonce"] ?? "");
      const sig = String(req.headers["x-signature"] ?? "");
      let ok = /^\d+$/.test(ts) && /^\d+$/.test(nonce);
      ok &&= Math.abs(Number(ts) - nowMs) <= 30_000;
      if (ok) {
        const canonical = [
          method.toUpperCase(),
          path,
          query,
          createHash("sha256").update(body).digest("hex"),
          ts,
          nonce,
        ].join("\n");
        try {
          ok =
            recoverAddress(keccak_256(Buffer.from(canonical)), sig) === agent;
        } catch {
          ok = false;
        }
      }
      if (ok && !["GET", "HEAD", "OPTIONS", "TRACE"].includes(method)) {
        const n = BigInt(nonce);
        ok = n > (lastNonce.get(agent) ?? -1n);
        if (ok) lastNonce.set(agent, n);
      }
      res.writeHead(ok ? 200 : 401, { "content-type": "application/json" });
      res.end(
        ok ? (method === "DELETE" ? "" : "{}") : '{"code":"UNAUTHORIZED"}',
      );
    });
  });
  await new Promise<void>((r) => server.listen(0, "127.0.0.1", r));
  const { port } = server.address() as AddressInfo;
  try {
    await run(`http://127.0.0.1:${port}`, received);
  } finally {
    await new Promise<void>((r) => server.close(() => r()));
  }
}

test("mock server: an agent-signed client sends exactly the agentAuth headers", async () => {
  const now = 1_776_033_900_123;
  const signer = AgentSigner.fromHex(VECTORS[1].private_key);
  await withAgentVerifier(now, async (baseUrl, received) => {
    const client = new Client({
      network: customNetwork({ label: "agent-mock", baseUrl, funds: "play" }),
      agentSigner: signer,
      nowMs: () => now,
      retry: { maxRetries: 0 },
    });

    await client.placeOrder({
      market_id: "BTC-USDX-PERP",
      side: "Buy",
      order_type: "Limit",
      quantity: "0.1",
      price: "50000",
      time_in_force: "GTC",
    });
    await client.getOrder("ord-1", "BTC-USDX-PERP"); // root route + query
    await client.cancelAllOrders();

    assert.equal(received.length, 3);
    const [post, get, del] = received;
    assert.equal(post.path, "/api/v1/orders");
    assert.equal(get.path, "/orders/ord-1");
    assert.equal(get.query, "market_id=BTC-USDX-PERP");
    assert.equal(del.method, "DELETE");

    for (const r of received) {
      // Exactly the four agent headers, and no HMAC or bearer credential.
      const authHeaders = Object.keys(r.headers)
        .filter((k) =>
          /^x-(agent|timestamp|nonce|signature|api-key)$|^authorization$/.test(
            k,
          ),
        )
        .sort();
      assert.deepEqual(authHeaders, [
        "x-agent",
        "x-nonce",
        "x-signature",
        "x-timestamp",
      ]);
      assert.equal(r.headers["x-agent"], VECTORS[1]["x-agent"]);
      assert.equal(r.headers["x-timestamp"], String(now));
    }
    // Nonces: the first is the timestamp, then strictly increasing.
    assert.deepEqual(
      received.map((r) => r.headers["x-nonce"]),
      [String(now), String(now + 1), String(now + 2)],
    );

    // The POST is byte-identical to what the signer produces for those exact
    // request bytes — i.e. the client signs the bytes it sends.
    assert.equal(
      post.headers["x-signature"],
      signer.sign({
        method: "POST",
        path: "/api/v1/orders",
        body: post.body,
        timestampMs: now,
        nonce: now,
      })["x-signature"],
    );
  });
});

test("mock server: a write whose nonce arrives out of order is refused (ENG-17010)", async () => {
  // Documents the caveat rather than fixing it: nonces are issued in order,
  // but if the higher one lands first the server rejects the lower one with
  // the same opaque 401 as a bad signature.
  const now = 1_776_033_900_000;
  const signer = AgentSigner.fromHex(VECTORS[1].private_key);
  const parts = { method: "DELETE", path: "/api/v1/orders", timestampMs: now };
  const first = signer.authHeaders(parts);
  const second = signer.authHeaders(parts);
  assert.ok(Number(second["x-nonce"]) > Number(first["x-nonce"]));

  await withAgentVerifier(now, async (baseUrl) => {
    const send = (h: AgentAuthHeaders) =>
      fetch(`${baseUrl}/api/v1/orders`, {
        method: "DELETE",
        headers: { ...h },
      });
    assert.equal((await send(second)).status, 200);
    assert.equal((await send(first)).status, 401);
  });
});

